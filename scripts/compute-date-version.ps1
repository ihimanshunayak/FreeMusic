# // Cyborg/ACC/Code/DateVersion — computes a date-based version for the
# // FreeMusic Android app and writes it into .gradle/version-date.properties
# // (gitignored) so that app/build.gradle.kts can read it as the source of
# // truth for `versionName` and `versionCode`.
# //
# // The script is invoked by `app/build.gradle.kts` at configuration time.
# // It is also safe to run by hand to preview the next version:
# //
# //   pwsh -File scripts/compute-date-version.ps1 -DryRun
# //
# // Date format produced:
# //
# //   1st same-day build : DD.MM.YY  (e.g. 16.10.26)
# //   Nth same-day build : DD.MM.YY.N
# //
# // versionCode is YYYYMMDD * 100 + N (capped at 99), giving the Play Store
# // a strictly increasing integer even when several builds ship the same
# // day. The counter is persisted in .gradle/version-date.properties so
# // subsequent builds on the same day keep incrementing and a build on a
# // later day starts over at .1.

[CmdletBinding()]
param(
    [switch] $DryRun,
    [string] $StateFile = ""  # Auto-detected below: <repo-root>/.gradle/version-date.properties
)

$ErrorActionPreference = "Stop"

# Resolve the repository root from the script's own location. We can't trust
# $PWD here: Gradle's `exec` runs the script with the *subproject's* CWD, so
# a relative ".gradle\..." path would land inside app/.gradle instead of the
# project root. Walking up from $PSScriptRoot to the first directory that has
# a settings.gradle.kts file gives us the canonical repo root.
if ([string]::IsNullOrEmpty($StateFile)) {
    $candidate = Split-Path -Parent $PSScriptRoot
    while ($candidate -and -not (Test-Path (Join-Path $candidate "settings.gradle.kts"))) {
        $parent = Split-Path -Parent $candidate
        if ($parent -eq $candidate) { break }
        $candidate = $parent
    }
    if (-not $candidate -or -not (Test-Path (Join-Path $candidate "settings.gradle.kts"))) {
        throw "compute-date-version.ps1: could not locate repo root (no settings.gradle.kts found above $PSScriptRoot)."
    }
    $StateFile = Join-Path $candidate ".gradle\version-date.properties"
}

function Get-State {
    param([string] $Path)
    $today = (Get-Date).ToString("yyyy-MM-dd")
    $counter = 0
    if (Test-Path $Path) {
        $props = @{}
        Get-Content $Path | ForEach-Object {
            if ($_ -match '^\s*([^=#]+)\s*=\s*(.*)\s*$') {
                $props[$Matches[1].Trim()] = $Matches[2].Trim()
            }
        }
        if ($props.ContainsKey("date") -and $props["date"] -eq $today) {
            $counter = [int]$props["counter"]
        }
    }
    [pscustomobject]@{ Date = $today; Counter = $counter }
}

function Save-State {
    param([string] $Path, [string] $Date, [int] $Counter, [string] $Base, [int] $Code)
    $dir = Split-Path -Parent $Path
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText(
        $Path,
        "# Auto-generated by scripts/compute-date-version.ps1`n" +
        "# Do not edit by hand -- this file is rewritten on every successful build.`n" +
        "date=$Date`n" +
        "counter=$Counter`n" +
        "base=$Base`n" +
        "code=$Code`n",
        $utf8NoBom
    )
}

function Format-VersionName {
    param([datetime] $Now, [int] $Counter)
    $base = "{0:D2}.{1:D2}.{2:D2}" -f $Now.Day, $Now.Month, ($Now.Year % 100)
    if ($Counter -le 1) { return $base }
    return "$base.$Counter"
}

function Format-VersionCode {
    param([datetime] $Now, [int] $Counter)
    $yyyymmdd = [int]($Now.ToString("yyyyMMdd"))
    $n = [Math]::Min([Math]::Max($Counter, 1), 99)
    return $yyyymmdd * 100 + $n
}

$now = Get-Date
$state = Get-State -Path $StateFile
$nextCounter = $state.Counter + 1
$versionName = Format-VersionName -Now $now -Counter $nextCounter
$versionCode = Format-VersionCode -Now $now -Counter $nextCounter

if ($DryRun) {
    Write-Host "DRY-RUN: would set base=$versionName, code=$versionCode, counter=$nextCounter"
    Write-Host "DRY-RUN: state file $StateFile would record date=$($state.Date) counter=$nextCounter"
    return
}

Save-State -Path $StateFile -Date $state.Date -Counter $nextCounter -Base $versionName -Code $versionCode
Write-Host "Set base=$versionName, code=$versionCode, counter=$nextCounter"
Write-Host "Persisted $StateFile (date=$($state.Date) counter=$nextCounter)"
